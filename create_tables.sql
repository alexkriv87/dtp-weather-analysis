 SELECT w.time_local AS "Время",
    EXTRACT(year FROM w.time_local)::integer AS "Год",
    EXTRACT(hour FROM w.time_local)::integer AS "Час",
    EXTRACT(month FROM w.time_local)::integer AS month_num,
        CASE EXTRACT(month FROM w.time_local)
            WHEN 1 THEN '01. Январь'::text
            WHEN 2 THEN '02. Февраль'::text
            WHEN 3 THEN '03. Март'::text
            WHEN 4 THEN '04. Апрель'::text
            WHEN 5 THEN '05. Май'::text
            WHEN 6 THEN '06. Июнь'::text
            WHEN 7 THEN '07. Июль'::text
            WHEN 8 THEN '08. Август'::text
            WHEN 9 THEN '09. Сентябрь'::text
            WHEN 10 THEN '10. Октябрь'::text
            WHEN 11 THEN '11. Ноябрь'::text
            WHEN 12 THEN '12. Декабрь'::text
            ELSE NULL::text
        END AS "Месяц",
    w.city_id,
    cc.city AS "Город",
        CASE
            WHEN w.temperature < '-10'::integer::numeric THEN '1. Мороз (< -10°C)'::text
            WHEN w.temperature >= '-10'::integer::numeric AND w.temperature <= '-3'::integer::numeric THEN '2. Холодно (-10°C до -3°C)'::text
            WHEN w.temperature >= '-3'::integer::numeric AND w.temperature <= 3::numeric THEN '3. Около нуля (-3°C до +3°C)'::text
            WHEN w.temperature >= 3::numeric AND w.temperature <= 10::numeric THEN '4. Прохладно (+3°C до +10°C)'::text
            WHEN w.temperature > 10::numeric THEN '5. Тепло (> +10°C)'::text
            ELSE NULL::text
        END AS "Температура",
        CASE
            WHEN w.snowfall > 0::numeric THEN '1. Снег'::text
            WHEN w.precipitation > 0::numeric AND w.snowfall = 0::numeric THEN '2. Дождь'::text
            ELSE '3. Нет осадков'::text
        END AS "Осадки",
        CASE
            WHEN w.wind_speed_10m < 2::numeric THEN '1. Штиль (<2 м/с)'::text
            WHEN w.wind_speed_10m >= 2::numeric AND w.wind_speed_10m <= 5::numeric THEN '2. Слабый (2-5 м/с)'::text
            WHEN w.wind_speed_10m >= 5::numeric AND w.wind_speed_10m <= 10::numeric THEN '3. Умеренный (5-10 м/с)'::text
            WHEN w.wind_speed_10m > 10::numeric THEN '4. Сильный (>10 м/с)'::text
            ELSE NULL::text
        END AS "Ветер",
        CASE
            WHEN w.cloud_cover < 20::numeric THEN '1. Ясно (<20%)'::text
            WHEN w.cloud_cover >= 20::numeric AND w.cloud_cover <= 60::numeric THEN '2. Переменная облачность (20-60%)'::text
            WHEN w.cloud_cover > 60::numeric THEN '3. Пасмурно (>60%)'::text
            ELSE NULL::text
        END AS "Облачность",
        CASE
            WHEN w.is_day = 1::numeric THEN 'День'::text
            ELSE 'Ночь'::text
        END AS "День",
        CASE
            WHEN gdm.fatalities > 0 AND gdm.injured > 0 THEN 'С погибшими и ранеными'::text
            WHEN gdm.fatalities > 0 THEN 'Только с погибшими'::text
            WHEN gdm.injured > 0 THEN 'Только с ранеными'::text
            ELSE 'Без пострадавших'::text
        END AS "Тип ДТП",
    count(DISTINCT gdm.id) AS "Количество ДТП",
    sum(gdm.fatalities) AS "Погибшие",
    sum(gdm.injured) AS "Раненые"
   FROM weather_clean w
     LEFT JOIN gibdd_dtp_main gdm ON w.city_id = gdm.city_id AND gdm.date = w.time_local::date AND EXTRACT(hour FROM gdm."time") = EXTRACT(hour FROM w.time_local)
     LEFT JOIN cities_clean cc ON w.city_id = cc.id
  GROUP BY w.time_local, w.city_id, cc.city, w.temperature, w.snowfall, w.precipitation, w.wind_speed_10m, w.cloud_cover, w.is_day, gdm.fatalities, gdm.injured;


