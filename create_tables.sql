            WHEN w.precipitation > 0::numeric AND w.snowfall = 0::numeric THEN 'Дождь'::text
            ELSE 'Нет осадков'::text
        END), (
        CASE
            WHEN w.cloud_cover < 20::numeric THEN 'Ясно'::text
            WHEN w.cloud_cover >= 20::numeric AND w.cloud_cover <= 60::numeric THEN 'Переменная облачность'::text
            WHEN w.cloud_cover > 60::numeric THEN 'Пасмурно'::text
            ELSE NULL::text
        END), (
        CASE
            WHEN w.wind_speed_10m < 2::numeric THEN 'Штиль'::text
            WHEN w.wind_speed_10m >= 2::numeric AND w.wind_speed_10m <= 5::numeric THEN 'Слабый ветер'::text
            WHEN w.wind_speed_10m >= 5::numeric AND w.wind_speed_10m <= 10::numeric THEN 'Умеренный ветер'::text
            WHEN w.wind_speed_10m > 10::numeric THEN 'Сильный ветер'::text
            ELSE NULL::text
        END)
