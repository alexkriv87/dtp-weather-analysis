        END) AS "Погодное сочетание",
    count(DISTINCT gdm.id) AS "Всего ДТП",
    count(*) AS "Всего часов",
    round(count(DISTINCT gdm.id)::numeric / count(*)::numeric, 3) AS "ДТП в час",
    sum(gdm.fatalities) AS "Всего погибших",
    round(sum(gdm.fatalities)::numeric / count(*)::numeric, 3) AS "Погибших в час"
   FROM weather_clean w
     LEFT JOIN gibdd_dtp_main gdm ON w.city_id = gdm.city_id AND gdm.date = w.time_local::date AND EXTRACT(hour FROM gdm."time") = EXTRACT(hour FROM w.time_local)
  GROUP BY (
        CASE
            WHEN w.temperature < '-10'::integer::numeric THEN 'Мороз (< -10°C)'::text
